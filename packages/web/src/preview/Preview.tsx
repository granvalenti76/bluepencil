import { useMemo } from "react";
import { renderMarkdown } from "./markdown.ts";

// Placeholders for the note numbers: private-use characters that Markdown lets through.
const OPEN = "\uE000";
const CLOSE = "\uE001";

/**
 * Preview: the text as the reader will read it (same column and typeface as the editor). It is a
 * snapshot of the text when it was opened: writing happens in the editor. In Review the notes
 * stay attached to the text with their numbers (`notes`, body positions).
 */
export function Preview({
  body,
  lang,
  notes = [],
}: {
  body: string;
  lang?: string;
  notes?: { pos: number; n: number }[];
}) {
  const html = useMemo(() => {
    let marked = body;
    for (const { pos, n } of [...notes].sort((a, b) => b.pos - a.pos))
      marked = marked.slice(0, pos) + `${OPEN}${n}${CLOSE}` + marked.slice(pos);
    return renderMarkdown(marked).replace(
      new RegExp(`${OPEN}(\\d+)${CLOSE}`, "g"),
      '<sup class="note-ref" aria-label="Note $1">$1</sup>',
    );
  }, [body, notes]);
  return (
    <article
      className="preview sheet"
      lang={lang}
      aria-label="Preview"
      // HTML generated by renderMarkdown: all the draft's text is escaped there.
      dangerouslySetInnerHTML={{ __html: html }}
    />
  );
}
